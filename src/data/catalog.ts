/** Turn a catalog entry into a watchlist instrument. Stocks get a placeholder demo seed price until live data loads. */
export function toInstrument(c: (typeof CATALOG)[number]): Instrument {
  const isCrypto = c.assetClass === 'crypto'
  return {
    symbol: c.symbol,
    name: c.name,
    assetClass: c.assetClass,
    feedId: isCrypto ? c.symbol.replace('/', '') : c.symbol,
    demoPrice: 100,
    demoVol: isCrypto ? 0.7 : 0.35,
  }
}
