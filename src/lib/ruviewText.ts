export type RuviewKey = keyof typeof RUVIEW_TEXT

export function ruviewText(lang: Lang, key: RuviewKey, vars: Record<string, string | number> = {}) {
  return RUVIEW_TEXT[key][lang].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`))
}

export function useRuviewT() {
  const lang = useLang()
  return (key: RuviewKey, vars?: Record<string, string | number>) => ruviewText(lang, key, vars)
}
